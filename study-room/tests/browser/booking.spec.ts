import { test, expect } from '@playwright/test';
import { dateLabel, nextSevenDays } from '../../src/core';
test('student can filter rooms, reserve a slot, reopen a saved pass, and cancel', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('textbox', { name: 'Student name' }).fill('Linh Nguyen');
  await page.getByRole('button', { name: 'Find my study space' }).click();
  await expect(page.getByText('Find your focus.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Capacity and equipment filters' }).click();
  await page.getByRole('button', { name: '20', exact: true }).click();
  await page.getByRole('button', { name: 'High-spec PC', exact: true }).click();
  await page.getByRole('button', { name: 'Show 1 rooms' }).click();
  await expect(page.getByRole('button', { name: /Code Lab, .*20 students/ })).toBeVisible();
  await page.getByRole('button', { name: /Code Lab, .*20 students/ }).click();
  await page.getByRole('button', { name: dateLabel(nextSevenDays()[1]), exact: true }).click();
  await page.getByRole('button', { name: /07:30–09:30 Available/ }).click();
  await page.getByRole('button', { name: 'Reserve room' }).click();
  await expect(page.getByText('VKU · YOUR BOOKING PASS')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Check in', exact: true })).toBeDisabled();
  await expect(page.locator('svg[width="190"]')).toBeVisible();
  await page.getByRole('button', { name: 'Close pass' }).click();
  await expect(page.getByRole('button', { name: /07:30–09:30 Booked/ })).toBeDisabled();
  await page.goto('/bookings');
  await expect(page.getByRole('button', { name: 'Open booking pass' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Open booking pass' })).toBeVisible();
  await page.getByRole('button', { name: 'Open booking pass' }).click();
  await expect(page.getByText('VKU · YOUR BOOKING PASS')).toBeVisible();
  await page.getByRole('button', { name: 'Close pass' }).click();
  await page.getByRole('button', { name: 'Cancel reservation' }).click();
  await page.getByRole('button', { name: 'Yes, remove reservation' }).click();
  await expect(page.getByText('Your next session starts here')).toBeVisible();
  expect(errors).toEqual([]);
  await page.goto('/');
  await page.getByRole('button', { name: 'Reset filters' }).click();
  await page.getByRole('img', { name: 'Illustrative study space photo' }).first().waitFor();
  await page.waitForFunction(() => Array.from(document.images).filter(img => img.src.includes('quiet')).some(img => img.complete && img.naturalWidth > 0));
  await page.screenshot({ path: 'artifacts/discover.png', fullPage: true });
});
